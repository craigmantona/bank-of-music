async function orderedRows(db, table, columns = "*") {
  return (await db.query(`select ${columns} from public.${table} order by id`)).rows;
}

test("verified repeat entries reuse approved recordings without changing catalogue or ratings", async () => {
  const db = await createFixture();
  try {
    const songsBefore = await orderedRows(db, "songs");
    const canonicalBefore = await orderedRows(db, "canonical_recordings");
    const ratingsBefore = await orderedRows(db, "song_ratings");

    await db.exec(operation);

    const repaired = (await db.query(`
      select id, song_id, canonical_song_id, musicbrainz_recording_id, match_status, match_method
      from public.quick_rate_collection_tracks
      where id in (2016, 2497)
      order by id
    `)).rows;
    assert.deepEqual(repaired, [
      {
        id: 2016,
        song_id: 19795,
        canonical_song_id: THREE_LIONS_CANONICAL,
        musicbrainz_recording_id: "9f03bee4-0c72-409b-9575-09a2f9c2fa7e",
        match_status: "direct_mbid",
        match_method: "bulk_verified_repeat"
      },
      {
        id: 2497,
        song_id: 19786,
        canonical_song_id: TRUE_CANONICAL,
        musicbrainz_recording_id: "a6ff57e9-5ba8-4a32-8ac3-e5e8c42796dc",
        match_status: "direct_mbid",
        match_method: "bulk_verified_repeat"
      }
    ]);

    const reviewOnly = (await db.query(`
      select song_id, canonical_song_id, match_status
      from public.quick_rate_collection_tracks where id = 3000
    `)).rows[0];
    assert.deepEqual(reviewOnly, {
      song_id: null,
      canonical_song_id: UNRELATED_CANONICAL,
      match_status: "unresolved"
    });
    assert.deepEqual(await orderedRows(db, "songs"), songsBefore);
    assert.deepEqual(await orderedRows(db, "canonical_recordings"), canonicalBefore);
    assert.deepEqual(await orderedRows(db, "song_ratings"), ratingsBefore);
    assert.equal((await db.query("select count(*)::int count from public.canonical_recordings")).rows[0].count, 5);
  } finally {
    await db.close();
  }
});

test("reconciliation aborts rather than replacing a rated placeholder", async () => {
  const db = await createFixture({ rateRepeatPlaceholder: true });
  try {
    const chartBefore = await orderedRows(
      db,
      "quick_rate_collection_tracks",
      "id, song_id, canonical_song_id, musicbrainz_recording_id, match_status, match_method"
    );
    const ratingsBefore = await orderedRows(db, "song_ratings");
    await assert.rejects(db.exec(operation), /rated or non-empty placeholder/);
    await db.exec("rollback");
    assert.deepEqual(
      await orderedRows(
        db,
        "quick_rate_collection_tracks",
        "id, song_id, canonical_song_id, musicbrainz_recording_id, match_status, match_method"
      ),
      chartBefore
    );
    assert.deepEqual(await orderedRows(db, "song_ratings"), ratingsBefore);
  } finally {
    await db.close();
  }
});
