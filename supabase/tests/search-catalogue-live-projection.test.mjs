after(async () => db?.close());

async function search(query, limit = 20) {
  return (await db.query(
    "select * from public.search_catalogue($1, $2)",
    [query, limit]
  )).rows;
}

test("backfill makes Status Quo searchable with its cached artist identity", async () => {
  const prefix = await search("statu");
  assert.equal(prefix[0].result_type, "artist");
  assert.equal(prefix[0].title, "Status Quo");
  assert.equal(prefix[0].external_id, "1884ed9c-6fe1-468d-a7f8-8d19c9c4e441");
  assert.equal(prefix[0].match_score, 350);

  const exact = await search("Status Quo");
  assert.equal(exact[0].result_type, "artist");
  assert.equal(exact[0].title, "Status Quo");
  assert.equal(exact[0].match_score, 500);
  assert.ok(exact.some(row => row.result_type === "album" && row.local_id === 1881));
});

test("migration preserves catalogue IDs, MusicBrainz links and ratings", async () => {
  const album = (await db.query(`
    select id, musicbrainz_release_id, musicbrainz_release_group_id
    from public.albums where id = 1881
  `)).rows[0];
  assert.deepEqual(album, {
    id: 1881,
    musicbrainz_release_id: "c0c832bc-f531-459f-ab3f-a871cda76c37",
    musicbrainz_release_group_id: "9ff08e45-a5f0-3299-8fb1-0b632dc14aaf"
  });
  assert.equal((await db.query("select rating::text from public.ratings")).rows[0].rating, "9");
  const result = (await search("Picturesque Matchstickable Messages"))
    .find(row => row.result_type === "album");
  assert.equal(result.local_id, 1881);
  assert.equal(result.community_average, "9.0000000000000000");
  assert.equal(result.community_count, 1);
});

test("newly imported artists, albums and tracks are searchable immediately", async () => {
  await db.exec(`
    insert into public.albums(title, artist, external_source, external_id)
    values ('Screamadelica', 'Primal Scream', 'musicbrainz', 'release-screamadelica');
    insert into public.songs(title, artist, album_id, external_source, external_id)
    select 'Movin on Up', 'Primal Scream', id, 'musicbrainz', 'recording-movin'
    from public.albums where title = 'Screamadelica';
  `);

  const rows = await search("primal");
  assert.equal(rows[0].result_type, "artist");
  assert.equal(rows[0].title, "Primal Scream");
  assert.ok(rows.some(row => row.result_type === "album" && row.title === "Screamadelica"));
  assert.ok(rows.some(row => row.result_type === "song" && row.title === "Movin on Up"));
});

test("projection follows edits and soft deletion without stale results", async () => {
  await db.exec(`
    update public.albums
    set artist = 'Primal Scream Updated', title = 'Screamadelica Updated'
    where title = 'Screamadelica';
  `);
  assert.ok((await search("updated")).some(row => row.title === "Screamadelica Updated"));

  await db.exec(`
    update public.albums set is_deleted = true
    where title = 'Screamadelica Updated';
  `);
  assert.equal((await search("Screamadelica Updated")).length, 0);
  assert.equal((await search("Primal Scream Updated")).length, 0);
});

test("projection is indexed, RLS-protected and read-only to clients", async () => {
  const properties = (await db.query(`
    select c.relkind, c.relrowsecurity
    from pg_class c
    where c.oid = 'public.search_catalogue_projection'::regclass
  `)).rows[0];
  assert.deepEqual(properties, { relkind: "r", relrowsecurity: true });

  const indexes = (await db.query(`
    select indexname from pg_indexes
    where schemaname = 'public'
      and tablename = 'search_catalogue_projection'
  `)).rows.map(row => row.indexname);
  assert.ok(indexes.includes("search_catalogue_projection_pkey"));
  assert.ok(indexes.includes("search_catalogue_projection_type_title_idx"));
  assert.ok(indexes.includes("search_catalogue_projection_title_idx"));

  const privileges = (await db.query(`
    select
      has_table_privilege('anon', 'public.search_catalogue_projection', 'select') as anon_select,
      has_table_privilege('anon', 'public.search_catalogue_projection', 'insert') as anon_insert,
      has_function_privilege('anon', 'public.search_catalogue(text,integer)', 'execute') as anon_search
  `)).rows[0];
  assert.deepEqual(privileges, {
    anon_select: true,
    anon_insert: false,
    anon_search: true
  });
});

test("one-edit and transposition fallback remains available", async () => {
  for (const query of ["Stats", "Stta"]) {
    const rows = await search(query);
    assert.ok(rows.some(row => row.result_type === "artist" && row.title === "Status Quo"), query);
  }
});

test("production-sized projection keeps strong and fallback searches bounded", async t => {
  // Warm the SQL functions before measuring execution rather than connection
  // and function compilation overhead.
  await search("statu");
  await search("zzzz-no-result-987654");

  for (const query of ["statu", "zzzz-no-result-987654"]) {
    const started = performance.now();
    await search(query);
    const elapsed = performance.now() - started;
    t.diagnostic(`${query}: ${elapsed.toFixed(1)}ms over 15k+ projected tracks`);
    assert.ok(elapsed < 750, `${query} took ${elapsed.toFixed(1)}ms`);
  }
});
