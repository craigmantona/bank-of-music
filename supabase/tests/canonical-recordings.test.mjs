import assert from "node:assert/strict";
import { after, before, test } from "node:test";
import { readFile } from "node:fs/promises";
import { createRequire } from "node:module";

const require = createRequire(process.env.CATALOGUE_TEST_PACKAGE || import.meta.url);
const { PGlite } = require("@electric-sql/pglite");
const migration = await readFile(new URL("../migrations/20261022150000_canonical_recording_identity.sql", import.meta.url), "utf8");
const user1 = "11111111-1111-4111-8111-111111111111";
const user2 = "22222222-2222-4222-8222-222222222222";
const mbid1 = "aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa";
const mbid2 = "bbbbbbbb-bbbb-4bbb-8bbb-bbbbbbbbbbbb";
const mbid3 = "cccccccc-cccc-4ccc-8ccc-cccccccccccc";
let db;

before(async () => {
  db = new PGlite();
  await db.exec(`
    create schema auth;
    create table auth.users(id uuid primary key);
    create function auth.uid() returns uuid language sql stable as 'select null::uuid';
    create table public.profiles(id uuid primary key, is_admin boolean default false);
    create role anon; create role authenticated; create role service_role bypassrls;
    create table public.songs(
      id bigint generated by default as identity primary key,
      title text not null, artist text not null, album_id bigint,
      external_source text, external_id text, canonical_song_id uuid,
      is_deleted boolean default false
    );
    create index songs_canonical_idx on public.songs(canonical_song_id);
    create table public.song_ratings(
      id bigint generated by default as identity primary key,
      user_id uuid not null references auth.users(id),
      song_id bigint references public.songs(id) on delete cascade,
      rating numeric not null, created_at timestamptz default timezone('utc',now()),
      unique(user_id,song_id)
    );
    create table public.quick_rate_collection_tracks(
      id bigint generated by default as identity primary key,
      collection_key text, chart_year integer, source_entry_key text
    );
    create view public.song_rating_charts as
      select s.id item_id,'song'::text item_type,s.title,s.artist,s.album_id,
        round(avg(r.rating),1) average_rating,count(r.rating) rating_count
      from song_ratings r join songs s on s.id=r.song_id
      group by s.id,s.title,s.artist,s.album_id;
    grant usage on schema public to anon,authenticated,service_role;
    grant select,insert,update,delete on songs,song_ratings,quick_rate_collection_tracks to service_role;
    insert into auth.users values ('${user1}'),('${user2}');
    insert into songs(title,artist,album_id,external_source,external_id) values
      ('Shared','Artist',1,'musicbrainz','${mbid1}'),
      ('Shared','Artist',2,'musicbrainz','${mbid1}'),
      ('Studio','Artist',3,'musicbrainz','${mbid2}'),
      ('Studio (live)','Artist',4,'musicbrainz','${mbid3}'),
      ('No identifier','Artist',5,'manual','manual-5');
    insert into song_ratings(user_id,song_id,rating) values
      ('${user1}',1,8),('${user1}',2,8),
      ('${user2}',1,6),('${user2}',2,9),
      ('${user1}',3,10);
  `);
  await db.exec(migration);
});

after(async () => { await db.close(); });

test("exact MBIDs seed stable shared canonical identities without title merging", async () => {
  const rows = (await db.query("select id,external_id,canonical_song_id from songs order by id")).rows;
  assert.equal((await db.query("select count(*)::int n from canonical_recordings")).rows[0].n, 3);
  assert.equal(rows[0].canonical_song_id, rows[1].canonical_song_id);
  assert.notEqual(rows[2].canonical_song_id, rows[3].canonical_song_id);
  assert.equal(rows[4].canonical_song_id, null);
  const firstId = rows[0].canonical_song_id;
  await db.query(`insert into canonical_recordings(title,artist,musicbrainz_recording_id,origin_key)
    values('Shared','Artist',$1,$2) on conflict(origin_key) do nothing`, [mbid1, `musicbrainz:${mbid1}`]);
  assert.equal((await db.query("select canonical_song_id from songs where id=1")).rows[0].canonical_song_id, firstId);
  assert.equal((await db.query("select count(*)::int n from canonical_recordings")).rows[0].n, 3);
});

test("rating audit collapses identical duplicates and flags conflicts", async () => {
  const audit = (await db.query("select status,legacy_row_count from canonical_rating_migration_audit order by user_id,status")).rows;
  assert.equal(audit.length, 3);
  assert.equal(audit.filter(row => row.status === "safe_duplicate_identical").length, 1);
  assert.equal(audit.filter(row => row.status === "safe_single").length, 1);
  assert.equal(audit.filter(row => row.status === "conflict").length, 1);
  assert.equal((await db.query("select count(*)::int n from song_ratings where canonical_song_id is not null")).rows[0].n, 2);
  assert.equal((await db.query("select count(*)::int n from song_ratings where canonical_song_id is null")).rows[0].n, 5);
});

test("one canonical rating projects to studio, compilation and Best Of occurrences once per user", async () => {
  const canonicalId = (await db.query("select canonical_song_id from songs where id=1")).rows[0].canonical_song_id;
  await db.query("insert into songs(title,artist,album_id,external_source,external_id,canonical_song_id) values('Shared','Artist',6,'manual','best-of',$1)", [canonicalId]);
  const charts = (await db.query("select item_id,rating_count,average_rating from song_rating_charts where item_id in (1,2,6) order by item_id")).rows;
  assert.deepEqual(charts.map(row => Number(row.rating_count)), [2,2,1]);
  assert.equal(Number(charts[0].average_rating), 7);
  assert.equal(Number(charts[1].average_rating), 8.5);
  assert.equal(Number(charts[2].average_rating), 8);
});

test("Quick Rate-first and album-first both resolve through one canonical rating", async () => {
  const created = (await db.query(`insert into canonical_recordings(title,artist,wikidata_qid,origin_key)
    values('Vogue','Madonna','Q999','quick-rate:uk-number-ones:vogue') returning id`)).rows[0];
  await db.query(`insert into quick_rate_collection_tracks(collection_key,chart_year,source_entry_key,canonical_song_id)
    values('uk-number-ones',1990,'vogue',$1)`, [created.id]);
  await db.query("insert into song_ratings(user_id,song_id,canonical_song_id,rating) values($1,null,$2,8)", [user1,created.id]);
  await db.query("insert into songs(title,artist,album_id,external_source,external_id,canonical_song_id) values('Vogue','Madonna',7,'manual','vogue-album',$1)", [created.id]);
  const inherited = await db.query("select average_rating from song_rating_charts where title='Vogue'");
  assert.equal(Number(inherited.rows[0].average_rating), 8);
  const laterMbid = "dddddddd-dddd-4ddd-8ddd-dddddddddddd";
  await db.query("update canonical_recordings set musicbrainz_recording_id=$1 where id=$2", [laterMbid,created.id]);
  await db.query("insert into songs(title,artist,album_id,external_source,external_id) values('Vogue','Madonna',9,'musicbrainz',$1)", [laterMbid]);
  assert.equal((await db.query("select canonical_song_id from songs where album_id=9")).rows[0].canonical_song_id, created.id);
  assert.equal((await db.query("select count(*)::int n from song_ratings where canonical_song_id=$1", [created.id])).rows[0].n, 1);

  const albumCanonical = (await db.query("select canonical_song_id from songs where id=1")).rows[0].canonical_song_id;
  await db.query(`insert into quick_rate_collection_tracks(collection_key,chart_year,source_entry_key,canonical_song_id)
    values('uk-number-ones',1991,'album-first',$1)`, [albumCanonical]);
  assert.equal((await db.query("select canonical_song_id from quick_rate_collection_tracks where source_entry_key='album-first'")).rows[0].canonical_song_id, albumCanonical);
});

test("trusted later MusicBrainz occurrences automatically reuse the seeded canonical UUID", async () => {
  await db.query("insert into songs(title,artist,album_id,external_source,external_id) values('Shared','Artist',8,'musicbrainz',$1)", [mbid1]);
  const ids = (await db.query("select distinct canonical_song_id from songs where external_id=$1", [mbid1])).rows;
  assert.equal(ids.length, 1);
});

test("deleting an occurrence preserves the canonical rating", async () => {
  const canonicalId = (await db.query("select canonical_song_id from songs where id=3")).rows[0].canonical_song_id;
  assert.equal((await db.query("select count(*)::int n from song_ratings where canonical_song_id=$1", [canonicalId])).rows[0].n, 1);
  await db.exec("delete from songs where id=3");
  assert.equal((await db.query("select count(*)::int n from song_ratings where canonical_song_id=$1", [canonicalId])).rows[0].n, 1);
});

test("canonical management is service-only while ratings retain owner policies", async () => {
  const grants = (await db.query(`select
    has_table_privilege('anon','canonical_recordings','select') anon_read,
    has_table_privilege('authenticated','canonical_recordings','insert') member_insert,
    has_table_privilege('service_role','canonical_recordings','update') service_update,
    has_table_privilege('authenticated','canonical_rating_migration_audit','select') audit_read`)).rows[0];
  assert.deepEqual(grants, { anon_read:true, member_insert:false, service_update:true, audit_read:false });
});
