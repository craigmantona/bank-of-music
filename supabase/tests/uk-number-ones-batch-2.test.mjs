async function tableDigest(db, table) {
  return (await db.query(`
    select
      count(*)::integer as count,
      pg_catalog.encode(
        extensions.digest(
          coalesce(
            string_agg(to_jsonb(row_value)::text, E'\\n' order by id),
            ''
          ),
          'sha256'
        ),
        'hex'
      ) as sha256
    from ${table} as row_value
  `)).rows[0];
}

async function stateSnapshot(db, tables = SNAPSHOT_TABLES) {
  return Object.fromEntries(
    await Promise.all(
      tables.map(async table => [table, await tableDigest(db, table)])
    )
  );
}

