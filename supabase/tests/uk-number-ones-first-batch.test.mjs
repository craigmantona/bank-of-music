test("an equal target rating is audited without duplication and can later be changed or cleared", async () => {
  const db = await createFixture();
  try {
    const inserted = await db.query(`
      insert into public.song_ratings (user_id, song_id, canonical_song_id, rating)
      values ('${USER_ONE}', null, '${PAPA_CANONICAL}', 8)
      returning id
    `);
    const targetRatingId = inserted.rows[0].id;
    const ratingCountBefore = (await db.query("select count(*)::int count from public.song_ratings")).rows[0].count;

    await db.exec(operation);

    assert.equal((await db.query("select count(*)::int count from public.song_ratings")).rows[0].count, ratingCountBefore);
    const [audit] = await orderedRows(
      db,
      "private.historical_chart_rating_reconciliation_audit",
      "source_rating::int as source_rating, reconciliation_status, target_song_rating_id"
    );
    assert.deepEqual(audit, {
      source_rating: 8,
      reconciliation_status: "already_equal",
      target_song_rating_id: targetRatingId
    });

    await db.exec(`update public.song_ratings set rating = 9 where id = ${targetRatingId}`);
    await db.exec(`delete from public.song_ratings where id = ${targetRatingId}`);
    assert.equal((await db.query(`select count(*)::int count from public.song_ratings where id = ${targetRatingId}`)).rows[0].count, 0);
    assert.equal((await db.query(`select count(*)::int count from private.historical_chart_rating_reconciliation_audit where target_song_rating_id = ${targetRatingId}`)).rows[0].count, 1);
    assert.equal((await db.query(`select rating::int as rating from public.song_ratings where canonical_song_id = '${PAPA_PLACEHOLDER}'`)).rows[0].rating, 8);
  } finally {
    await db.close();
  }
});

