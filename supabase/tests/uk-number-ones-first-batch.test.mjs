async function orderedRows(db, table, columns = "*") {
  return (await db.query(`select ${columns} from ${table} order by id`)).rows;
}

async function stateSnapshot(db) {
  return {
    albums: await orderedRows(db, "public.albums"),
    canonicals: await orderedRows(db, "public.canonical_recordings"),
    songs: await orderedRows(db, "public.songs"),
    chart: await orderedRows(db, "public.quick_rate_collection_tracks"),
    ratings: await orderedRows(db, "public.song_ratings"),
    historical: await orderedRows(db, "public.historical_chart_entry_ratings"),
    audit: await orderedRows(db, "private.historical_chart_rating_reconciliation_audit")
  };
}

async function rejectAndRollback(db, pattern) {
  await assert.rejects(db.exec(operation), pattern);
  await db.exec("rollback");
}

