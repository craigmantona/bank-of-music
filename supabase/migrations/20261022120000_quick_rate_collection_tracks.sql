begin;

create table public.quick_rate_collection_tracks (
  id bigint generated by default as identity primary key,
  collection_key text not null,
  chart_year integer not null check (chart_year between 1952 and 2100),
  source_entry_key text not null,
  source_name text not null default 'wikimedia',
  source_url text not null,
  source_revision text,
  wikidata_qid text check (wikidata_qid is null or wikidata_qid ~ '^Q[1-9][0-9]*$'),
  title text not null,
  artist text not null,
  first_number_one_date date,
  weeks_at_number_one integer check (weeks_at_number_one is null or weeks_at_number_one > 0),
  number_one_runs integer not null default 1 check (number_one_runs > 0),
  musicbrainz_recording_id text check (
    musicbrainz_recording_id is null or
    musicbrainz_recording_id ~* '^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$'
  ),
  isrc text,
  spotify_track_id text,
  song_id bigint references public.songs(id) on delete set null,
  match_status text not null check (match_status in ('direct_mbid', 'identifier', 'title_artist', 'unresolved', 'ambiguous')),
  match_method text,
  match_notes text,
  source_metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  unique (collection_key, chart_year, source_entry_key)
);

comment on table public.quick_rate_collection_tracks is
  'Read-only Quick Rate collection evidence imported from Wikimedia/Wikidata and optionally linked to an existing BOM song occurrence.';
comment on column public.quick_rate_collection_tracks.song_id is
  'Nullable existing catalogue occurrence. Imports never create songs automatically.';

create index quick_rate_collection_tracks_collection_year_idx
  on public.quick_rate_collection_tracks (collection_key, chart_year);
create index quick_rate_collection_tracks_mbid_idx
  on public.quick_rate_collection_tracks (musicbrainz_recording_id)
  where musicbrainz_recording_id is not null;

alter table public.quick_rate_collection_tracks enable row level security;

create policy "Quick Rate collections are publicly readable"
  on public.quick_rate_collection_tracks
  for select
  to anon, authenticated
  using (true);

revoke all on table public.quick_rate_collection_tracks from public, anon, authenticated;
grant select on table public.quick_rate_collection_tracks to anon, authenticated;
grant all on table public.quick_rate_collection_tracks to service_role;

revoke all on sequence public.quick_rate_collection_tracks_id_seq from public, anon, authenticated;
grant usage, select on sequence public.quick_rate_collection_tracks_id_seq to service_role;

commit;
